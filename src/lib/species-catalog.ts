const BOTTOM_GENERA =
  /ancistrus|pl[ée]co|corydoras|brochis|aspidoras|dianema|scleromystax|pangio|kuhli|\bloches?\b|botia|yasuhikotakia|otocinclus|hypancistrus|peckoltia|parotocinclus|rineloricaria|farlowella|synodontis|apistogramma|crossocheilus/i;
export function swimZoneByName(
  name: string,
  scientific?: string | null,
): SwimZone | null {
  const n = norm(name);
  const sci = scientific ? norm(scientific) : "";
  const hit = SPECIES_CATALOG.find(
    (c) =>
      norm(c.commonName) === n ||
      norm(c.scientificName) === n ||
      (sci !== "" && norm(c.scientificName) === sci),
  );
  if (hit) return hit.swimZone;
  if (BOTTOM_GENERA.test(`${name} ${scientific ?? ""}`)) return "bottom";
  return null;
}

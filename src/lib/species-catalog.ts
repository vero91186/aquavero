export function schoolMinOf(
  ref: Pick<
    SpeciesReference,
    "temperament" | "adultSizeCm" | "category" | "commonName"
  > & { scientificName?: string },
): number | null {
  if (ref.scientificName && GROUP_MIN[ref.scientificName] !== undefined)
    return GROUP_MIN[ref.scientificName];
  // Hors table : règle générale sur le tempérament « grégaire » et la taille.
  if (!/grégaire/i.test(ref.temperament)) return null;
  if (ref.category === "invertebrate")
    return /crevette/i.test(ref.commonName) ? 6 : null;
  if (ref.adultSizeCm <= 3.5) return 8;
  if (ref.adultSizeCm <= 6.5) return 6;
  return 5;
}

